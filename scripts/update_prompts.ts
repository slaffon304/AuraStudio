async function updatePrompts() {
  console.log('Updating generation_prompts in database...');
  for (const [key, body] of Object.entries(prompts)) {
    const res = await pool.query(
      `INSERT INTO generation_prompts (key, body, updated_at)
       VALUES ($1, $2, NOW())
       ON CONFLICT (key) DO UPDATE SET body = EXCLUDED.body, updated_at = NOW()
       RETURNING key`,
      [key, body.trim()]
    );
    console.log(`Updated key: ${res.rows[0].key} (${body.trim().length} chars)`);
  }
  console.log('All prompts successfully updated in database!');
  await pool.end();
}

